#!/usr/bin/env python3
"""Generate the mixed-layout TPC-H query set (benchmarks/tpch/queries-mixed).

Mixed layout: the six dimension tables live in PostgreSQL, the two fact
tables in Hive. Every table reference in the stock queries is qualified with
its catalog and schema, so one SQL text runs unchanged on Arneb (started with
tpch-mixed.toml) and on the bundled Trino (with no default catalog — a missed
reference then fails instead of silently reading the all-Hive layout).

All 22 stock queries use explicit JOIN syntax, so every table reference sits
right after FROM or JOIN; anchoring on those keywords leaves
`EXTRACT(YEAR FROM o_orderdate)` and column aliases such as `AS nation`
alone. The script refuses to write anything if a table name is still
unqualified afterwards.

Usage:
    python3 benchmarks/tpch/scripts/qualify_queries.py            # regenerate
    python3 benchmarks/tpch/scripts/qualify_queries.py --check    # CI-style diff
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIMENSIONS = ("nation", "region", "customer", "supplier", "part", "partsupp")
FACTS = ("orders", "lineitem")
TABLES = DIMENSIONS + FACTS

RELATION = re.compile(r"(?i)\b(FROM|JOIN)(\s+)(" + "|".join(TABLES) + r")\b(?!\s*\.)")
# A table name in relation position that is NOT preceded by a qualifier.
UNQUALIFIED = re.compile(r"(?i)\b(?:FROM|JOIN)\s+(" + "|".join(TABLES) + r")\b(?!\s*\.)")


def qualify(sql: str, hive_schema: str, pg_schema: str) -> str:
    def target(m: re.Match) -> str:
        table = m.group(3).lower()
        prefix = f"postgresql.{pg_schema}" if table in DIMENSIONS else f"hive.{hive_schema}"
        return f"{m.group(1)}{m.group(2)}{prefix}.{table}"

    out = RELATION.sub(target, sql)
    left = UNQUALIFIED.findall(out)
    if left:
        raise ValueError(f"unqualified table reference(s) left: {left}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=ROOT / "queries")
    ap.add_argument("--dst", type=Path, default=ROOT / "queries-mixed")
    ap.add_argument("--hive-schema", default="tpch")
    ap.add_argument("--pg-schema", default="tpch_mixed")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if --dst differs from what would be generated")
    args = ap.parse_args()

    header = (f"-- GENERATED by benchmarks/tpch/scripts/qualify_queries.py from ../queries — do not edit.\n"
              f"-- Mixed layout: dimensions in postgresql.{args.pg_schema}, facts in hive.{args.hive_schema}.\n")
    stale = []
    sources = sorted(args.src.glob("q*.sql"))
    if not sources:
        print(f"no queries under {args.src}", file=sys.stderr)
        return 2
    for src in sources:
        try:
            body = qualify(src.read_text(), args.hive_schema, args.pg_schema)
        except ValueError as e:
            print(f"{src.name}: {e}", file=sys.stderr)
            return 1
        text = header + body
        dst = args.dst / src.name
        if args.check:
            if not dst.exists() or dst.read_text() != text:
                stale.append(src.name)
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
    if args.check and stale:
        print(f"queries-mixed is stale: {', '.join(stale)}", file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(sources)} queries → {args.dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
